#!/usr/bin/env bash
# Dotfiles installation script (idempotent)
set -e

DOTFILES_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
TIMESTAMP="$(date '+%Y%m%d_%H%M%S')"

echo "=================================================="
echo "🚀 Installing dotfiles from: $DOTFILES_DIR"
echo "📍 Target Home: $HOME"
echo "=================================================="

# ----------------------------------------------------
# Helper: backup a file with a timestamp
# ----------------------------------------------------
backup_if_exists() {
    local target="$1"
    if [ -f "$target" ] && [ ! -L "$target" ]; then
        local backup="${target}.bak.${TIMESTAMP}"
        cp "$target" "$backup"
        echo "📦 Backed up $target -> $backup"
    fi
}

# ----------------------------------------------------
# 1. Idempotent dotfiles loader in ~/.bashrc
# ----------------------------------------------------
LOADER_START="# >>> dotfiles loader >>>"
LOADER_END="# <<< dotfiles loader <<<"

if [ -f "$HOME/.bashrc" ] && grep -Fq "$LOADER_START" "$HOME/.bashrc"; then
    echo "ℹ️  Dotfiles loader already present in $HOME/.bashrc"
else
    if [ -f "$HOME/.bashrc" ]; then
        backup_if_exists "$HOME/.bashrc"
        # Ensure a trailing newline exists before appending
        if [ -s "$HOME/.bashrc" ] && [ -n "$(tail -c 1 "$HOME/.bashrc")" ]; then
            echo "" >> "$HOME/.bashrc"
        fi
    fi

    echo "📝 Appending dotfiles loader to $HOME/.bashrc ..."
    cat << EOF >> "$HOME/.bashrc"

$LOADER_START
# Generated by dotfiles install.sh
export DOTFILES_DIR="$DOTFILES_DIR"
if [ -f "\$DOTFILES_DIR/.bashrc" ]; then
    source "\$DOTFILES_DIR/.bashrc"
fi
$LOADER_END
EOF
    echo "✅ Loader appended to ~/.bashrc"
fi

# ----------------------------------------------------
# 2. Main Git configuration include
# ----------------------------------------------------
if git config --global --get-all include.path 2>/dev/null | grep -Fxq "$DOTFILES_DIR/.gitconfig"; then
    echo "ℹ️  Git global include already configured: $DOTFILES_DIR/.gitconfig"
else
    echo "🔧 Configuring Git global include..."
    git config --global include.path "$DOTFILES_DIR/.gitconfig"
    echo "✅ Git configured to include $DOTFILES_DIR/.gitconfig"
fi

# ----------------------------------------------------
# 3. Handle single local configuration (.bashrc.local)
# ----------------------------------------------------
if [ ! -f "$HOME/.bashrc.local" ]; then
    if [ -f "$DOTFILES_DIR/.bashrc.local" ]; then
        cp "$DOTFILES_DIR/.bashrc.local" "$HOME/.bashrc.local"
        echo "✅ Copied .bashrc.local to $HOME/.bashrc.local"
    elif [ -f "$DOTFILES_DIR/.bashrc.local.template" ]; then
        cp "$DOTFILES_DIR/.bashrc.local.template" "$HOME/.bashrc.local"
        echo "⚠️  Created $HOME/.bashrc.local from template — please edit it with your settings."
    fi
else
    echo "ℹ️  $HOME/.bashrc.local exists"
fi

# Source local config to read user settings (GIT_USER_NAME, SSH_KEYS, etc.)
if [ -f "$HOME/.bashrc.local" ]; then
    # shellcheck source=/dev/null
    source "$HOME/.bashrc.local"
fi

# ----------------------------------------------------
# 4. Configure local Git settings (~/.gitconfig.local)
# ----------------------------------------------------
if [ -f "$HOME/.gitconfig.local" ]; then
    echo "ℹ️  $HOME/.gitconfig.local exists (preserving existing configuration)"
else
    if [ -f "$DOTFILES_DIR/.gitconfig.local.template" ]; then
        cp "$DOTFILES_DIR/.gitconfig.local.template" "$HOME/.gitconfig.local"
        echo "⚠️  Created ~/.gitconfig.local from template"
    else
        touch "$HOME/.gitconfig.local"
        echo "ℹ️  Created empty ~/.gitconfig.local"
    fi

    # Sync git identity if configured in environment / .bashrc.local
    if [ -n "${GIT_USER_NAME:-}" ]; then
        git config --file "$HOME/.gitconfig.local" user.name "$GIT_USER_NAME"
    fi
    if [ -n "${GIT_USER_EMAIL:-}" ]; then
        git config --file "$HOME/.gitconfig.local" user.email "$GIT_USER_EMAIL"
    fi
    if [ -n "${GIT_USER_NAME:-}" ] && [ -n "${GIT_USER_EMAIL:-}" ]; then
        echo "✅ Git identity configured in ~/.gitconfig.local: $GIT_USER_NAME <$GIT_USER_EMAIL>"
    fi
fi

# ----------------------------------------------------
# 5. Validate SSH keys & detect PuTTY (.ppk) issues
# ----------------------------------------------------
validate_ssh_keys() {
    echo "🔑 Validating SSH keys configuration..."
    mkdir -p "$HOME/.ssh"
    chmod 700 "$HOME/.ssh" 2>/dev/null || true

    if [ -n "${SSH_KEYS+x}" ] && [ ${#SSH_KEYS[@]} -gt 0 ]; then
        for key in "${SSH_KEYS[@]}"; do
            if [ -f "$key" ]; then
                if [[ "$key" == *.ppk ]]; then
                    echo "  ⚠️ PuTTY format (.ppk): $key"
                    echo "     OpenSSH cannot read .ppk files. In PuTTYgen: Conversions -> Export OpenSSH key."
                else
                    local fp
                    fp=$(ssh-keygen -lf "$key" 2>/dev/null | awk '{print $1, $2, $4}' || true)
                    if [ -n "$fp" ]; then
                        echo "  ✓ Valid OpenSSH key: $key ($fp)"
                    else
                        echo "  ⚠️ Key file exists but failed to read: $key"
                    fi
                fi
            else
                if [ -f "${key}.ppk" ]; then
                    echo "  ⚠️ Key not found: $key"
                    echo "     💡 Found PuTTY key: ${key}.ppk"
                    echo "     💡 Fix: Open PuTTYgen -> Load '${key}.ppk' -> Conversions -> Export OpenSSH key -> Save as '$key'"
                else
                    echo "  ⚠️ Key not found: $key"
                fi
            fi
        done
    else
        echo "  ℹ️  No SSH_KEYS defined in ~/.bashrc.local"
    fi
}

validate_ssh_keys

# ----------------------------------------------------
# 6. Azure DevOps host entry in ~/.ssh/config (optional)
# ----------------------------------------------------
if [ -n "${AZURE_SSH_KEY:-}" ]; then
    SSH_CONFIG="$HOME/.ssh/config"
    mkdir -p "$HOME/.ssh"
    chmod 700 "$HOME/.ssh" 2>/dev/null || true

    if [ ! -f "$SSH_CONFIG" ] || ! grep -q "ssh.dev.azure.com" "$SSH_CONFIG" 2>/dev/null; then
        echo "🌐 Adding Azure DevOps entry to ~/.ssh/config..."
        cat << EOF >> "$SSH_CONFIG"

Host ssh.dev.azure.com vs-ssh.visualstudio.com
    HostName ssh.dev.azure.com
    IdentityFile $AZURE_SSH_KEY
    IdentitiesOnly yes
    PubkeyAcceptedKeyTypes +ssh-rsa
EOF
        chmod 600 "$SSH_CONFIG" 2>/dev/null || true
        echo "✅ Configured Azure DevOps in ~/.ssh/config"
    else
        echo "ℹ️  Azure DevOps entry already present in ~/.ssh/config"
    fi
else
    echo "ℹ️  No AZURE_SSH_KEY specified, skipping Azure DevOps SSH configuration"
fi

# ----------------------------------------------------
# 7. Install / Update GitReview dotnet tool
# ----------------------------------------------------
echo "🔍 Checking for .NET CLI & GitReview tool..."
if command -v dotnet >/dev/null 2>&1; then
    if dotnet tool list -g | grep -q "wieseknows.gitreview"; then
        echo "🔄 Updating wieseknows.GitReview tool..."
        dotnet tool update -g wieseknows.GitReview || echo "⚠️ Failed to update GitReview tool"
    else
        echo "📦 Installing wieseknows.GitReview tool..."
        dotnet tool install -g wieseknows.GitReview || echo "⚠️ Failed to install GitReview tool"
    fi
else
    echo "⚠️ .NET SDK (dotnet) not found in PATH. Skipping GitReview installation."
fi

# ----------------------------------------------------
# 8. Windows-specific sanity checks (GIT_SSH hijack)
# ----------------------------------------------------
if [ -n "${GIT_SSH:-}" ]; then
    echo "🚨 WARNING: GIT_SSH is set to: $GIT_SSH"
    echo "    If this points at TortoiseGitPlink, OpenSSH ssh-agent keys won't be used."
fi
SSH_CMD_GLOBAL="$(git config --global --get core.sshCommand 2>/dev/null || true)"
if [ -n "$SSH_CMD_GLOBAL" ]; then
    echo "🚨 WARNING: git core.sshCommand (global) is set to: $SSH_CMD_GLOBAL"
fi

# Warn if any local config files are tracked in git repo
for f in .bashrc.local .gitconfig.local; do
    if [ -f "$DOTFILES_DIR/$f" ]; then
        if git -C "$DOTFILES_DIR" ls-files --error-unmatch "$f" >/dev/null 2>&1; then
            echo "🚨 WARNING: $f is committed to the dotfiles repo!"
            echo "    Remove it with: git -C \"$DOTFILES_DIR\" rm --cached $f"
        fi
    fi
done

echo ""
echo "=================================================="
echo "✅ Dotfiles installation complete!"
echo "=================================================="
echo "📌 Restart your terminal or run: source ~/.bashrc"
echo "=================================================="
echo ""

# Keep window open if run interactively (so user can read logs)
if [ -t 0 ] && [ -z "${NONINTERACTIVE:-}" ] && [ -z "${CI:-}" ]; then
    read -rp "Press Enter to exit..." _
fi
