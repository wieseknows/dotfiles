#!/usr/bin/env bash
# Dotfiles installation script (idempotent)
set -e

DOTFILES_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
TIMESTAMP="$(date '+%Y%m%d_%H%M%S')"
RECONFIGURE=0

for arg in "$@"; do
    case "$arg" in
        --reconfigure|-r)
            RECONFIGURE=1
            ;;
    esac
done

echo "=================================================="
echo "🚀 Installing dotfiles from: $DOTFILES_DIR"
echo "📍 Target Home: $HOME"
echo "=================================================="

# ----------------------------------------------------
# Helper: backup a file with a timestamp
# ----------------------------------------------------
backup_if_exists() {
    local target="$1"
    if [ -f "$target" ] && [ ! -L "$target" ]; then
        local backup="${target}.bak.${TIMESTAMP}"
        if [ ! -f "$backup" ]; then
            cp "$target" "$backup"
            echo "📦 Backed up $target -> $backup"
        fi
    fi
}

# ----------------------------------------------------
# 1. Idempotent dotfiles loader in ~/.bashrc
# ----------------------------------------------------
LOADER_START="# >>> dotfiles loader >>>"
LOADER_END="# <<< dotfiles loader <<<"
LEGACY_MARKER="# AUTO-GENERATED LOADER FOR DOTFILES"

if [ -f "$HOME/.bashrc" ] && grep -Fq "$LEGACY_MARKER" "$HOME/.bashrc"; then
    backup_if_exists "$HOME/.bashrc"
    tmp_bashrc="$(mktemp)"
    awk '
        /^# =+$/ {
            if (in_legacy) {
                if (seen_fi) {
                    in_legacy = 0
                    skip_blank = 1
                }
                next
            }
            prev_sep = $0
            next
        }
        prev_sep != "" && /^# AUTO-GENERATED LOADER FOR DOTFILES$/ {
            in_legacy = 1
            seen_fi = 0
            prev_sep = ""
            next
        }
        prev_sep != "" {
            print prev_sep
            prev_sep = ""
        }
        in_legacy {
            if (/^# >>> dotfiles loader >>>$/) {
                in_legacy = 0
                print
                next
            }
            if (/^fi$/) {
                seen_fi = 1
            }
            next
        }
        skip_blank && /^$/ {
            skip_blank = 0
            next
        }
        {
            skip_blank = 0
            print
        }
        END {
            if (prev_sep != "") {
                print prev_sep
            }
        }
    ' "$HOME/.bashrc" > "$tmp_bashrc" && mv "$tmp_bashrc" "$HOME/.bashrc"
    echo "🧹 Removed legacy dotfiles loader from $HOME/.bashrc"
fi

if [ -f "$HOME/.bashrc" ] && grep -Fq "$LOADER_START" "$HOME/.bashrc"; then
    echo "ℹ️  Dotfiles loader already present in $HOME/.bashrc"
else
    if [ -f "$HOME/.bashrc" ]; then
        backup_if_exists "$HOME/.bashrc"
        # Ensure a trailing newline exists before appending
        if [ -s "$HOME/.bashrc" ] && [ -n "$(tail -c 1 "$HOME/.bashrc")" ]; then
            echo "" >> "$HOME/.bashrc"
        fi
    fi

    echo "📝 Appending dotfiles loader to $HOME/.bashrc ..."
    cat << EOF >> "$HOME/.bashrc"

$LOADER_START
# Generated by dotfiles install.sh
export DOTFILES_DIR="$DOTFILES_DIR"
if [ -f "\$DOTFILES_DIR/.bashrc" ]; then
    source "\$DOTFILES_DIR/.bashrc"
fi
$LOADER_END
EOF
    echo "✅ Loader appended to ~/.bashrc"
fi

# ----------------------------------------------------
# 2. Main Git configuration include
# ----------------------------------------------------
DOTFILES_GITCONFIG="$DOTFILES_DIR/.gitconfig"
DOTFILES_GITCONFIG_WIN="$(cd "$DOTFILES_DIR" && pwd -W 2>/dev/null || true)/.gitconfig"

if git config --global --get-all include.path 2>/dev/null | grep -F -e "$DOTFILES_GITCONFIG" -e "$DOTFILES_GITCONFIG_WIN" -q; then
    echo "ℹ️  Git global include already configured: $DOTFILES_DIR/.gitconfig"
else
    echo "🔧 Configuring Git global include..."
    git config --global --add include.path "$DOTFILES_DIR/.gitconfig"
    echo "✅ Git configured to include $DOTFILES_DIR/.gitconfig"
fi

# ----------------------------------------------------
# 3. Manage local configuration (~/.bashrc.local)
# ----------------------------------------------------
is_interactive() {
    [ -t 0 ] && [ -z "${NONINTERACTIVE:-}" ] && [ -z "${CI:-}" ]
}

escape_bash_dq() {
    printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

detect_default_ssh_keys() {
    local candidate
    for candidate in "$HOME/.ssh/id_ed25519" "$HOME/.ssh/id_rsa"; do
        if [ -f "$candidate" ]; then
            printf '%s\n' "$candidate"
        fi
    done
}

default_projects_root() {
    case "$(uname -s 2>/dev/null || true)" in
        MINGW*|MSYS*|CYGWIN*) printf '%s' "/c/dev/projects" ;;
        *) printf '%s' "$HOME/projects" ;;
    esac
}

prompt_with_default() {
    local prompt_text="$1"
    local default_val="$2"
    local reply
    if [ -n "$default_val" ]; then
        read -rp "$prompt_text [$default_val]: " reply
        printf '%s' "${reply:-$default_val}"
    else
        read -rp "$prompt_text: " reply
        printf '%s' "$reply"
    fi
}

prompt_required() {
    local prompt_text="$1"
    local val="$2"
    if [ -n "$val" ]; then
        val="$(prompt_with_default "$prompt_text" "$val")"
    fi
    while [ -z "$val" ]; do
        val="$(prompt_with_default "$prompt_text" "")"
        [ -z "$val" ] && echo "  ⚠️ $prompt_text is required." >&2
    done
    printf '%s' "$val"
}

prompt_secret() {
    local prompt_text="$1"
    local reply
    read -rsp "$prompt_text (hidden, Enter to skip): " reply
    echo "" >&2
    printf '%s' "$reply"
}

write_bashrc_local() {
    local git_name="$1"
    local git_email="$2"
    local azure_key="$3"
    local provider="$4"
    local openrouter_model="$5"
    local openrouter_key="$6"
    local gemini_key="$7"
    local deepseek_key="$8"
    local projects_root="$9"
    shift 9
    local ssh_keys=("$@")

    {
        echo "# =============================================================================="
        echo "# LOCAL CONFIGURATION (Generated by dotfiles install.sh)"
        echo "# =============================================================================="
        echo ""
        echo "# 1. Git Identity"
        if [ -n "$git_name" ]; then
            echo "export GIT_USER_NAME=\"$(escape_bash_dq "$git_name")\""
        fi
        if [ -n "$git_email" ]; then
            echo "export GIT_USER_EMAIL=\"$(escape_bash_dq "$git_email")\""
        fi
        echo ""
        echo "# 2. SSH Keys"
        echo "SSH_KEYS=("
        for k in "${ssh_keys[@]}"; do
            [ -n "$k" ] && echo "    \"$(escape_bash_dq "$k")\""
        done
        echo ")"
        if [ -n "$azure_key" ]; then
            echo "export AZURE_SSH_KEY=\"$(escape_bash_dq "$azure_key")\""
        fi
        echo ""
        echo "# 3. API Keys & AI Providers"
        echo "export GIT_REVIEW_PROVIDER=\"$(escape_bash_dq "$provider")\""
        echo "export OPENROUTER_MODEL=\"$(escape_bash_dq "$openrouter_model")\""
        if [ -n "$openrouter_key" ]; then
            echo "export OPENROUTER_API_KEY=\"$(escape_bash_dq "$openrouter_key")\""
        fi
        if [ -n "$gemini_key" ]; then
            echo "export GEMINI_API_KEY=\"$(escape_bash_dq "$gemini_key")\""
        fi
        if [ -n "$deepseek_key" ]; then
            echo "export DEEPSEEK_API_KEY=\"$(escape_bash_dq "$deepseek_key")\""
        fi
        echo ""
        echo "# 4. Project Navigation (\`proj <alias>\`)"
        echo "export PROJECTS_ROOT=\"$(escape_bash_dq "$projects_root")\""
        echo ""
        echo "declare -g -A PROJECT_PATHS=("
        echo "    # [\"app\"]=\"my-app/web\""
        echo ")"
    } > "$HOME/.bashrc.local"
}

generate_bashrc_local() {
    local git_name="${GIT_USER_NAME:-$(git config --global user.name 2>/dev/null || true)}"
    local git_email="${GIT_USER_EMAIL:-$(git config --global user.email 2>/dev/null || true)}"
    local azure_key="${AZURE_SSH_KEY:-}"
    local provider="${GIT_REVIEW_PROVIDER:-openrouter}"
    local openrouter_model="${OPENROUTER_MODEL:-poolside/laguna-s-2.1:free}"
    local openrouter_key="${OPENROUTER_API_KEY:-}"
    local gemini_key="${GEMINI_API_KEY:-}"
    local deepseek_key="${DEEPSEEK_API_KEY:-}"
    local projects_root="${PROJECTS_ROOT:-$(default_projects_root)}"

    local ssh_keys=()
    local detected_key
    while IFS= read -r detected_key; do
        [ -n "$detected_key" ] && ssh_keys+=("$detected_key")
    done < <(detect_default_ssh_keys)

    if is_interactive; then
        echo ""
        echo "🛠️  Interactive setup for local machine settings (~/.bashrc.local)"
        echo "   Press Enter to accept defaults in [brackets] or leave optional fields blank."
        echo ""

        git_name="$(prompt_required "Git User Name" "$git_name")"
        git_email="$(prompt_required "Git Email" "$git_email")"

        local default_ssh_str=""
        if [ ${#ssh_keys[@]} -gt 0 ]; then
            default_ssh_str="$(IFS=,; echo "${ssh_keys[*]}")"
        fi
        local ssh_input
        ssh_input="$(prompt_with_default "SSH key paths (comma-separated, or 'none')" "$default_ssh_str")"
        ssh_keys=()
        if [ -n "$ssh_input" ] && [ "$ssh_input" != "none" ]; then
            local raw_item
            IFS=',' read -ra raw_items <<< "$ssh_input"
            for raw_item in "${raw_items[@]}"; do
                raw_item="$(echo "$raw_item" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
                [ -n "$raw_item" ] && ssh_keys+=("$raw_item")
            done
        fi

        azure_key="$(prompt_with_default "Azure DevOps SSH key (optional)" "$azure_key")"
        projects_root="$(prompt_with_default "Projects root directory (PROJECTS_ROOT)" "$projects_root")"

        local configure_ai
        read -rp "Configure AI / GitReview API keys now? [y/N]: " configure_ai
        if [[ "$configure_ai" =~ ^[Yy]$ ]]; then
            provider="$(prompt_with_default "Default AI provider (openrouter/gemini/deepseek)" "$provider")"
            openrouter_model="$(prompt_with_default "OpenRouter model" "$openrouter_model")"
            openrouter_key="$(prompt_secret "OpenRouter API Key")"
            gemini_key="$(prompt_secret "Gemini API Key")"
            deepseek_key="$(prompt_secret "DeepSeek API Key")"
        fi
    fi

    write_bashrc_local \
        "$git_name" "$git_email" "$azure_key" \
        "$provider" "$openrouter_model" "$openrouter_key" "$gemini_key" "$deepseek_key" \
        "$projects_root" "${ssh_keys[@]}"

    echo "✅ Generated $HOME/.bashrc.local"
}

if [ ! -f "$HOME/.bashrc.local" ] || [ "$RECONFIGURE" = "1" ]; then
    if [ -f "$HOME/.bashrc.local" ]; then
        backup_if_exists "$HOME/.bashrc.local"
    fi
    generate_bashrc_local
    FORCE_SYNC_GIT_IDENTITY=1
else
    echo "ℹ️  $HOME/.bashrc.local exists (run with --reconfigure to update interactively)"
fi

# Source local config to read user settings (GIT_USER_NAME, SSH_KEYS, etc.)
if [ -f "$HOME/.bashrc.local" ]; then
    # shellcheck source=/dev/null
    source "$HOME/.bashrc.local"
fi

# ----------------------------------------------------
# 4. Configure local Git settings (~/.gitconfig.local)
# ----------------------------------------------------
if [ ! -f "$HOME/.gitconfig.local" ]; then
    touch "$HOME/.gitconfig.local"
    echo "✅ Created $HOME/.gitconfig.local"
    FORCE_SYNC_GIT_IDENTITY=1
else
    echo "ℹ️  $HOME/.gitconfig.local exists"
fi

if [ "${FORCE_SYNC_GIT_IDENTITY:-0}" = "1" ]; then
    # Sync git identity if configured in environment / .bashrc.local
    if [ -n "${GIT_USER_NAME:-}" ]; then
        git config --file "$HOME/.gitconfig.local" user.name "$GIT_USER_NAME"
    fi
    if [ -n "${GIT_USER_EMAIL:-}" ]; then
        git config --file "$HOME/.gitconfig.local" user.email "$GIT_USER_EMAIL"
    fi
    if [ -n "${GIT_USER_NAME:-}" ] && [ -n "${GIT_USER_EMAIL:-}" ]; then
        echo "✅ Git identity configured in ~/.gitconfig.local: $GIT_USER_NAME <$GIT_USER_EMAIL>"
    fi
fi

# ----------------------------------------------------
# 5. Validate SSH keys & detect PuTTY (.ppk) issues
# ----------------------------------------------------
validate_ssh_keys() {
    echo "🔑 Validating SSH keys configuration..."
    mkdir -p "$HOME/.ssh"
    chmod 700 "$HOME/.ssh" 2>/dev/null || true

    if [ -n "${SSH_KEYS+x}" ] && [ ${#SSH_KEYS[@]} -gt 0 ]; then
        for key in "${SSH_KEYS[@]}"; do
            if [ -f "$key" ]; then
                if [[ "$key" == *.ppk ]]; then
                    echo "  ⚠️ PuTTY format (.ppk): $key"
                    echo "     OpenSSH cannot read .ppk files. In PuTTYgen: Conversions -> Export OpenSSH key."
                else
                    local fp
                    fp=$(ssh-keygen -lf "$key" 2>/dev/null | awk '{print $1, $2, $4}' || true)
                    if [ -n "$fp" ]; then
                        echo "  ✓ Valid OpenSSH key: $key ($fp)"
                    else
                        echo "  ⚠️ Key file exists but failed to read: $key"
                    fi
                fi
            else
                if [ -f "${key}.ppk" ]; then
                    echo "  ⚠️ Key not found: $key"
                    echo "     💡 Found PuTTY key: ${key}.ppk"
                    echo "     💡 Fix: Open PuTTYgen -> Load '${key}.ppk' -> Conversions -> Export OpenSSH key -> Save as '$key'"
                else
                    echo "  ⚠️ Key not found: $key"
                fi
            fi
        done
    else
        echo "  ℹ️  No SSH_KEYS defined; ~/.bashrc will auto-detect OpenSSH keys in ~/.ssh"
    fi
}

validate_ssh_keys

# ----------------------------------------------------
# 6. Azure DevOps host entry in ~/.ssh/config (optional)
# ----------------------------------------------------
if [ -n "${AZURE_SSH_KEY:-}" ]; then
    SSH_CONFIG="$HOME/.ssh/config"
    mkdir -p "$HOME/.ssh"
    chmod 700 "$HOME/.ssh" 2>/dev/null || true

    if [ ! -f "$SSH_CONFIG" ] || ! grep -q "ssh.dev.azure.com" "$SSH_CONFIG" 2>/dev/null; then
        echo "🌐 Adding Azure DevOps entry to ~/.ssh/config..."
        cat << EOF >> "$SSH_CONFIG"

Host ssh.dev.azure.com vs-ssh.visualstudio.com
    HostName ssh.dev.azure.com
    IdentityFile $AZURE_SSH_KEY
    IdentitiesOnly yes
    PubkeyAcceptedKeyTypes +ssh-rsa
EOF
        chmod 600 "$SSH_CONFIG" 2>/dev/null || true
        echo "✅ Configured Azure DevOps in ~/.ssh/config"
    else
        echo "ℹ️  Azure DevOps entry already present in ~/.ssh/config"
    fi
else
    echo "ℹ️  No AZURE_SSH_KEY specified, skipping Azure DevOps SSH configuration"
fi

# ----------------------------------------------------
# 7. Install / Update GitReview dotnet tool (optional)
# ----------------------------------------------------
if [ "${INSTALL_GITREVIEW:-1}" = "1" ]; then
    echo "🔍 Checking for .NET CLI & GitReview tool..."
    if command -v dotnet >/dev/null 2>&1; then
        if dotnet tool list -g | grep -q "wieseknows.gitreview"; then
            echo "🔄 Updating wieseknows.GitReview tool..."
            dotnet tool update -g wieseknows.GitReview || echo "⚠️ Failed to update GitReview tool"
        else
            echo "📦 Installing wieseknows.GitReview tool..."
            dotnet tool install -g wieseknows.GitReview || echo "⚠️ Failed to install GitReview tool"
        fi
    else
        echo "⚠️ .NET SDK (dotnet) not found in PATH. Skipping GitReview installation."
    fi
else
    echo "ℹ️  Skipping GitReview installation (INSTALL_GITREVIEW=0)"
fi

# ----------------------------------------------------
# 8. Sanity checks (GIT_SSH hijack, duplicates, tracked secrets)
# ----------------------------------------------------
if [ -f "$HOME/.bashrc" ]; then
    loader_count=$(grep -cE 'source[[:space:]]+.*DOTFILES_DIR/\.bashrc' "$HOME/.bashrc" 2>/dev/null || true)
    if [ "${loader_count:-0}" -gt 1 ]; then
        echo "🚨 WARNING: Multiple dotfiles loaders ($loader_count) detected in $HOME/.bashrc."
        echo "    Remove duplicate blocks so ~/.bashrc only sources dotfiles once."
    fi
fi

include_count=$(git config --global --get-all include.path 2>/dev/null | grep -F -c -e "$DOTFILES_GITCONFIG" -e "$DOTFILES_GITCONFIG_WIN" || true)
if [ "${include_count:-0}" -gt 1 ]; then
    echo "🚨 WARNING: Duplicate Git include.path entries ($include_count) for $DOTFILES_GITCONFIG in ~/.gitconfig."
fi

if [ -n "${GIT_SSH:-}" ]; then
    echo "🚨 WARNING: GIT_SSH is set to: $GIT_SSH"
    echo "    If this points at TortoiseGitPlink, OpenSSH ssh-agent keys won't be used."
fi
SSH_CMD_GLOBAL="$(git config --global --get core.sshCommand 2>/dev/null || true)"
if [ -n "$SSH_CMD_GLOBAL" ]; then
    echo "🚨 WARNING: git core.sshCommand (global) is set to: $SSH_CMD_GLOBAL"
fi

# Warn if any local config files are tracked in git repo
for f in .bashrc.local .gitconfig.local; do
    if [ -f "$DOTFILES_DIR/$f" ]; then
        if git -C "$DOTFILES_DIR" ls-files --error-unmatch "$f" >/dev/null 2>&1; then
            echo "🚨 WARNING: $f is committed to the dotfiles repo!"
            echo "    Remove it with: git -C \"$DOTFILES_DIR\" rm --cached $f"
        fi
    fi
done

echo ""
echo "=================================================="
echo "✅ Dotfiles installation complete!"
echo "=================================================="
echo "📌 Restart your terminal or run: source ~/.bashrc"
echo "=================================================="
echo ""

# Keep window open if run interactively (so user can read logs)
if [ -t 0 ] && [ -z "${NONINTERACTIVE:-}" ] && [ -z "${CI:-}" ]; then
    read -rp "Press Enter to exit..." _
fi
